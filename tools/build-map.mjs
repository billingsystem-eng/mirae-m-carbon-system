// Builds public/js/<out>.js (an SVG outline of one country) from Natural Earth (public domain).
//   node tools/build-map.mjs "South Korea" public/js/kr-map.js
// The page projects site coordinates with the same Mercator formula as monitor.html's mapXY():
//   x = tx + k * lon(rad),  y = ty - k * ln(tan(pi/4 + lat/2))
const [name = 'South Korea', out = 'public/js/kr-map.js'] = process.argv.slice(2);
const URL = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_countries.geojson';
import fs from 'node:fs';

const res = await fetch(URL);
if (!res.ok) throw new Error('Natural Earth download failed: ' + res.status);
const gj = await res.json();
const f = gj.features.find((x) => [x.properties.NAME, x.properties.ADMIN, x.properties.NAME_LONG].includes(name));
if (!f) throw new Error('Country not found: ' + name);
const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;

const rad = (d) => d * Math.PI / 180;
const my = (lat) => Math.log(Math.tan(Math.PI / 4 + rad(lat) / 2));
let x1 = 1e9, x2 = -1e9, y1 = 1e9, y2 = -1e9;
for (const p of polys) for (const ring of p) for (const [lon, lat] of ring) {
  x1 = Math.min(x1, rad(lon)); x2 = Math.max(x2, rad(lon)); y1 = Math.min(y1, my(lat)); y2 = Math.max(y2, my(lat));
}
const W = 520, PAD = 16;
const k = (W - 2 * PAD) / (x2 - x1);
const H = Math.round((y2 - y1) * k + 2 * PAD);
const tx = PAD - k * x1, ty = PAD + k * y2;
const X = (lon) => tx + k * rad(lon), Y = (lat) => ty - k * my(lat);

let d = '';
for (const p of polys) for (const ring of p) {
  let last = null, seg = [];
  for (const [lon, lat] of ring) {
    const x = +X(lon).toFixed(1), y = +Y(lat).toFixed(1);
    if (last && last[0] === x && last[1] === y) continue; // drop points that collapse at 0.1 precision
    seg.push([x, y]); last = [x, y];
  }
  if (seg.length < 4) continue; // specks
  d += 'M' + seg.map((s) => s.join(',')).join('L') + 'Z';
}
fs.writeFileSync(out, `// Generated by tools/build-map.mjs from Natural Earth (public domain). Do not edit by hand.\nwindow.REGION_MAP = ${JSON.stringify({ w: W, h: H, k: +k.toFixed(4), tx: +tx.toFixed(4), ty: +ty.toFixed(4), d })};\n`);
console.log(`${name}: ${W}x${H}, ${(d.length / 1024).toFixed(0)} KB path ->`, out);
